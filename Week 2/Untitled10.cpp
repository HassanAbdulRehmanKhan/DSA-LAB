#include<iostream>
using namespace std;
int main(){
	int day = 4;
	switch(day){
		case 1:
			cout<<"Monday";
			break;
		case 2:
			cout<<"Tuesday";
			break;
			case 3:
				cout<<"wednesday";
				break;
				case 4:
					cout<<"thursday";
					break;
					default:
						cout<<"Enter valid day";
				
	}
}
